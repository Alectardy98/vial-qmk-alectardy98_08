#!/usr/bin/env python3
"""Repack the existing Satisfaction Bongo Cat and Apple SVG for the memory LCD.

Requires Pillow and rsvg-convert. Output is row-major, MSB-left, 1=black.
"""
from pathlib import Path
import re
import subprocess
import tempfile

from PIL import Image

keyboard = Path(__file__).resolve().parents[1]
source = keyboard.parent / "satisfactional/keymaps/vial/oled/bongocat.c"
original = source.read_text()
parts = [original.split('#include "quantum.h"')[0].rstrip(), """
// Repacked from satisfactional/keymaps/vial/oled/bongocat.c; original art retained.
// Apple silhouette: assets/apple.svg, Simple Icons (CC0),
// https://github.com/simple-icons/simple-icons/blob/develop/icons/apple.svg
// Generated by tools/generate_display_assets.py. MSB-left; set bits are black.
#pragma once
#include <stdint.h>
""".strip()]


def pack(image):
    return [sum((image.getpixel((x + bit, y)) == 0) << (7 - bit) for bit in range(8))
            for y in range(image.height) for x in range(0, image.width, 8)]


def array(name, frames):
    size = len(frames[0])
    parts.append(f"static const uint8_t {name}[{len(frames)}][{size}] = {{")
    for data in frames:
        parts.append("    {")
        for i in range(0, len(data), 16):
            parts.append("        " + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + ",")
        parts.append("    },")
    parts.append("};\n")


for name in ("idle", "prep", "tap"):
    body = original.split(" " + name + "[")[1].split("= {", 1)[1].split("\n    };", 1)[0]
    frames = []
    for frame in re.findall(r"\{([^{}]+)\}", body):
        data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", frame))
        assert len(data) == 512
        image = Image.new("1", (96, 32), 1)
        for y in range(32):
            for x in range(96):
                if data[x + 128 * (y // 8)] & (1 << (y % 8)):
                    image.putpixel((x, y), 0)
        # The unused right edge of the original 128-pixel canvas is blank.
        assert all(data[x + page * 128] == 0 for page in range(4) for x in range(96, 128))
        frames.append(pack(image))
    array("bongo_" + name, frames)

with tempfile.TemporaryDirectory() as directory:
    png = Path(directory) / "apple.png"
    subprocess.run(["rsvg-convert", "-w", "48", "-h", "48", "-o", str(png),
                    str(keyboard / "assets/apple.svg")], check=True)
    rgba = Image.open(png).convert("RGBA")
    mask = Image.new("1", (48, 48), 1)
    for y in range(48):
        for x in range(48):
            if rgba.getpixel((x, y))[3] >= 128:
                mask.putpixel((x, y), 0)
    array("apple_logo", [pack(mask)])

(keyboard / "display_assets.h").write_text("\n\n".join(parts) + "\n")
print("Generated", keyboard / "display_assets.h")

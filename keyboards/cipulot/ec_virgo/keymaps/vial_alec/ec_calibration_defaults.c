void ec_apply_calibration_defaults(void) {
    for (uint8_t row = 0; row < MATRIX_ROWS; row++) {
        for (uint8_t col = 0; col < MATRIX_COLS; col++) {
            ec_config.noise_floor[row][col] = EC_NOISE_FLOOR[row][col];
            ec_config.bottoming_reading[row][col] = EC_BOTTOMING[row][col];
            ec_config.bottoming_calibration_starter[row][col] = false;

            eeprom_ec_config.bottoming_reading[row][col] = EC_BOTTOMING[row][col];

            ec_config.rescaled_mode_0_actuation_threshold[row][col] = EC_APC_ACT[row][col];
            ec_config.rescaled_mode_0_release_threshold[row][col] = EC_APC_REL[row][col];
            ec_config.rescaled_mode_1_initial_deadzone_offset[row][col] = EC_RT_DZ[row][col];
            ec_config.rescaled_mode_1_actuation_offset[row][col] = EC_RT_ACT[row][col];
            ec_config.rescaled_mode_1_release_offset[row][col] = EC_RT_REL[row][col];
        }
    }

    eeconfig_update_kb_datablock(&eeprom_ec_config, 0, EECONFIG_KB_DATA_SIZE);
}

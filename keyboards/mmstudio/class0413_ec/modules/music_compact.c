#include "audio.h"
#ifndef PITCH_STANDARD_A
#define PITCH_STANDARD_A 440.0f
#endif
_Static_assert(PITCH_STANDARD_A==440.0f,"Revalidate encoded table for new pitch standard");
_Static_assert(FLT_RADIX==2 && FLT_MANT_DIG==24 && sizeof(float)==4,"binary32 required");
static const uint32_t octave_base[12]={0x4102d012U,0x410a9761U,0x4112d516U,0x411b9041U,0x4124d055U,0x412e9d36U,0x4138ff49U,0x4143ff6cU,0x414fa6ffU,0x415c0000U,0x416914f9U,0x4176f10eU};
static const uint8_t octave_correction[128]={0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0xc4,0x78,0x8a,0x96,0x58,0x8a,0xc4,0x78,0x8a,0x96,0x58,0x8a,0xa6,0x88,0x89,0x97,0x78,0x89,0xa4,0x88,0x89,0x97,0x68,0x89,0xa6,0x88,0x89,0x96,0x68,0x89,0xa6,0x88,0x89,0x97,0x78,0x89,0xc4,0x78,0x8a,0x96,0x58,0x8a,0xc4,0x78,0x8a,0x96,0x58,0x8a,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0xd2,0x68,0x8b,0xb4,0x48,0x8d,0xd2,0x68,0x8b,0xb4,0x48,0x8d,0xd2,0x68,0x8b,0xb4,0x48,0x8d,0xd2,0x68,0x8b,0xb4,0x48,0x8d,0xd2,0x68,0x8b,0xb4,0x48,0x8d,0xd2,0x68,0x8b,0xb4,0x48,0x8d,0xd2,0x68,0x8b,0xb4,0x48,0x8d,0xd2,0x68,0x8b};
float __wrap_compute_freq_for_midi_note(uint8_t note){
    unsigned delta=(octave_correction[note/2]>>((note&1)*4))&15;
    uint32_t bits=octave_base[note%12]+((uint32_t)(note/12)<<23)+delta-8;
    float frequency;memcpy(&frequency,&bits,sizeof frequency);return frequency;
}
void __wrap_process_audio_noteon(uint8_t note){play_note(__wrap_compute_freq_for_midi_note(note),0xF);}
void __wrap_process_audio_noteoff(uint8_t note){stop_note(__wrap_compute_freq_for_midi_note(note));}

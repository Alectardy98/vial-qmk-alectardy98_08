#pragma once
/* Wire/record ABI shared by C firmware and the Qt client. Physical acquisition,
 * eligible positions, record magic and EEPROM placement are board contracts. */
#define EC42_MAJOR 2
#define EC42_MINOR 9
#define EC42_REPORT_BYTES 32
#define EC42_PAYLOAD_BYTES 20
#define EC42_ADC_MAX 1023
#define EC42_STORAGE_FORMAT 1
#define EC42_RECORD_BYTES(rows,cols) (17U+3U*(rows)*(cols))
enum ec42_opcode {
 EC42_HELLO=0x10, EC42_LATCH=0x11, EC42_READ_PAGE=0x12, EC42_READ_CELL=0x13,
 EC42_CAL_STATUS=0x14, EC42_CONFIG=0x15, EC42_BACKUP=0x16,
 EC42_RESTORE_BEGIN=0x17, EC42_RESTORE_CHUNK=0x18, EC42_RESTORE_COMMIT=0x19,
 EC42_ABORT=0x1b, EC42_FIRMWARE_INFO=0x1c, EC42_ACTIVE_RECORD=0x1d,
 EC42_CAL_CONTROL=0x20, EC42_RESERVED_21=0x21, EC42_CAL_VALIDATE=0x22,
 EC42_CAL_PROPOSAL=0x23, EC42_CAL_ACTIVATE=0x24, EC42_CAL_SAVE=0x25,
 EC42_RESERVED_26=0x26, EC42_CAPTURE_EVIDENCE=0x27,
 EC42_ACTUATION_GET=0x28, EC42_ACTUATION_SET=0x29, EC42_RT_SET=0x2a,
 EC42_DESCRIPTOR=0x2b
};
enum ec42_status {EC42_OK=0,EC42_MALFORMED=1,EC42_UNSUPPORTED=2,EC42_RANGE=3,EC42_STALE=4};
